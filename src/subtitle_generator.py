"""상단 고정 훅 타이틀 + 중앙 상황 설명 자막 + 속마음 대사를 하나의 .ass 파일로 생성."""
from __future__ import annotations

import re
from pathlib import Path

from PIL import ImageDraw, Image

from .fonts import FontInfo, get_font
from .utils import HEIGHT, TEMP_DIR, WIDTH

# ---- 레이아웃 (1080x1920) ----
TITLE_CENTER_Y = 250        # 상단 타이틀 영역 160~340
THOUGHT_TOP_Y = 470         # 영상 상단부 (Y≈480)
NARRATION_CENTER_Y = 1220   # 영상 하단부 (Y≈1220)
MAX_TEXT_W = 980

TITLE_SIZE = 86
NARRATION_SIZE = 58
THOUGHT_SIZE = 60

COLORS = {
    "green": "&H90EE90&",
    "pink": "&HC1B6FF&",
    "yellow": "&H00D7FF&",
    "white": "&HFFFFFF&",
    "skyblue": "&HFFCE87&",
}

TAG_RE = re.compile(r"\{[^}]*\}")


def _ts(sec: float) -> str:
    sec = max(0.0, sec)
    cs = int(round(sec * 100))
    h, cs = divmod(cs, 360000)
    m, cs = divmod(cs, 6000)
    s, cs = divmod(cs, 100)
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def _norm(text: str) -> str:
    """실제 줄바꿈 문자를 ASS 줄바꿈(\\N)으로 통일."""
    return text.replace("\r\n", "\\N").replace("\n", "\\N").replace("\\n", "\\N").strip()


def _plain(text: str) -> str:
    return TAG_RE.sub("", text)


class _Measurer:
    def __init__(self, font: FontInfo):
        self.font = font
        self._d = ImageDraw.Draw(Image.new("RGB", (1, 1)))
        self._cache: dict[int, object] = {}

    def width(self, text: str, size: int) -> float:
        f = self._cache.setdefault(size, self.font.pil(size))
        return max((self._d.textlength(_plain(l), font=f) for l in text.split("\\N")), default=0)


def _auto_break(text: str, size: int, m: _Measurer, max_w: int = MAX_TEXT_W) -> str:
    """\\N이 없고 너무 길면 가운데에 가까운 공백에서 2줄로 나눈다."""
    if "\\N" in text or m.width(text, size) <= max_w:
        return text
    plain_spaces = [i for i, c in enumerate(text) if c == " "]
    if not plain_spaces:
        return text
    mid = len(text) / 2
    cut = min(plain_spaces, key=lambda i: abs(i - mid))
    return text[:cut] + "\\N" + text[cut + 1:]


def _fit_scale(text: str, size: int, m: _Measurer, max_w: int = MAX_TEXT_W) -> str:
    """그래도 넘치면 가로 스케일(\\fscx)로 화면 안에 맞춘다."""
    w = m.width(text, size)
    if w <= max_w:
        return ""
    s = max(55, int(100 * max_w / w))
    return f"\\fscx{s}\\fscy{max(s, 85)}"


def _color(value: str | None, idx: int) -> str:
    if value and value.startswith("&H"):
        return value if value.endswith("&") else value + "&"
    if value and value.lower() in COLORS:
        return COLORS[value.lower()]
    return COLORS["green"] if idx % 2 == 0 else COLORS["pink"]


def build_ass(script: dict, duration: float, out_path: Path = TEMP_DIR / "subtitles.ass",
              speed: float = 1.0, font: FontInfo | None = None) -> Path:
    """script.json 내용을 .ass로 변환.

    duration: 최종 출력 영상 길이(초, 배속 적용 후)
    speed   : 원본 배속. 스크립트 타임스탬프(원본 기준)를 출력 타임라인으로 환산한다.
    """
    font = font or get_font()
    m = _Measurer(font)
    fam = font.family

    header = f"""[Script Info]
; Generated by zipsa-shorts subtitle_generator
ScriptType: v4.00+
PlayResX: {WIDTH}
PlayResY: {HEIGHT}
WrapStyle: 2
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Title,{fam},{TITLE_SIZE},&H00FFFFFF,&H00FFFFFF,&H00000000,&H96000000,-1,0,0,0,100,100,0,0,1,8,5,5,40,40,0,1
Style: Narration,{fam},{NARRATION_SIZE},&H00FFFFFF,&H00FFFFFF,&H00000000,&H80000000,-1,0,0,0,100,100,0,0,1,6,3,5,40,40,0,1
Style: Thought,{fam},{THOUGHT_SIZE},&H0090EE90,&H00FFFFFF,&H00000000,&H80000000,-1,-1,0,0,100,100,0,0,1,5,3,8,40,40,0,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events: list[str] = []

    def add(layer: int, start: float, end: float, style: str, text: str) -> None:
        start, end = max(0.0, start), min(duration, end)
        if end - start < 0.05:
            return
        events.append(f"Dialogue: {layer},{_ts(start)},{_ts(end)},{style},,0,0,0,,{text}")

    # 1) 상단 고정 타이틀 (처음~끝)
    tt = script.get("top_title") or {}
    l1, l2 = _norm(tt.get("line1", "")), _norm(tt.get("line2", ""))
    title = "\\N".join(x for x in (l1, l2) if x)
    if title:
        fit = _fit_scale(title, TITLE_SIZE, m)
        add(5, 0, duration, "Title",
            f"{{\\an5\\pos({WIDTH // 2},{TITLE_CENTER_Y})\\c&HFFFFFF&{fit}}}{title}")

    # 2) 상황 자막 / 속마음
    thought_idx = 0
    for sub in script.get("subtitles", []):
        try:
            start = float(sub["start"]) / speed
            end = float(sub["end"]) / speed
        except (KeyError, TypeError, ValueError):
            continue
        text = _norm(str(sub.get("text", "")))
        if not text:
            continue
        kind = sub.get("type", "narration")
        if kind == "thought":
            core = text.strip()
            if not core.startswith("*"):
                core = f"* {core}"
            if not core.endswith("*"):
                core = f"{core} *"
            core = _auto_break(core, THOUGHT_SIZE, m)
            fit = _fit_scale(core, THOUGHT_SIZE, m)
            col = _color(sub.get("color"), thought_idx)
            thought_idx += 1
            # 팝업 애니메이션 (80% → 105% → 100%). 폭이 넘치는 경우엔 고정 스케일만 적용.
            anim = fit or "\\fscx80\\fscy80\\t(0,160,\\fscx105\\fscy105)\\t(160,260,\\fscx100\\fscy100)"
            add(3, start, end, "Thought",
                f"{{\\an8\\pos({WIDTH // 2},{THOUGHT_TOP_Y})\\i1\\c{col}\\fad(150,150){anim}}}{core}")
        else:
            core = _auto_break(text, NARRATION_SIZE, m)
            fit = _fit_scale(core, NARRATION_SIZE, m)
            add(2, start, end, "Narration",
                f"{{\\an5\\pos({WIDTH // 2},{NARRATION_CENTER_Y})\\fad(120,120){fit}}}{core}")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    # BOM 포함 UTF-8: Windows 환경의 libass/에디터 호환성 확보
    out_path.write_text(header + "\n".join(events) + "\n", encoding="utf-8-sig")
    return out_path
